  let v12ContactMatch=null,v12Rows=[],v12CurrentEdit='',v12Starting=false;
  const v12RelLabels=new Set(['mom','dad','mother','father','wife','husband','son','daughter',
    'brother','sister','aunt','uncle','grandmother','grandfather','other family member']);

  function v12NewRow(m={}){
    const arrived=(m.checkins||[]).includes($('workingDate').value);
    return {id:m.id||uid('fam'),masterId:m.masterId||'',name:m.name||'',
      relationship:m.relationship||'',mobile:m.mobile||'',
      checkins:[...(m.checkins||[])],selected:arrived,alreadyArrived:arrived};
  }
  function v12ContactName(group){
    const v=(state.volunteers||[]).find(x=>x.id===group?.volunteerId);
    return group?.contactName||v&&volName(v)||'';
  }
  function v12SetVisible(){
    const form=$('v36RegistrationForm'),modal=$('v36RegistrationModal');
    if(!form||!modal)return;
    const family=modal.classList.contains('open')&&
      /family/.test($('v36RegistrationType')?.value||'');
    form.classList.toggle('v12-family-active',family);
    if($('v12FamilyPanel'))$('v12FamilyPanel').hidden=!family;
    // The original selector, old family browser and autogenerated head row
    // must not appear a second time.
    if(family){
      $('v36RegistrationTitle').textContent=v36RegistrationEditKey?'EDIT REGISTRATION':'NEW REGISTRATION';
      $('v12ContactName').required=true;
      $('v12ContactPhone').required=true;
    }
  }
